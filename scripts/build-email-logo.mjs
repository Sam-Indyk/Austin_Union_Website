// Builds the small seal embedded in every email (src/lib/email/logo.ts).
// Embedding it means the logo shows even in mail apps that block web images.
//   node scripts/build-email-logo.mjs [source.png]
import { writeFileSync } from 'node:fs';
import sharp from 'sharp';

const src = process.argv[2] ?? 'public/media/site/seal.png';
// 2x the 64px it is shown at, for sharp screens; a palette PNG keeps it ~6 KB.
const png = await sharp(src).resize(128, 128, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } }).png({ compressionLevel: 9, palette: true, quality: 90 }).toBuffer();
writeFileSync(
  'src/lib/email/logo.ts',
  `// Generated by scripts/build-email-logo.mjs from ${src} — do not edit by hand.
export const LOGO_PNG_BASE64 =
  '${png.toString('base64')}';
`,
);
console.log(`src/lib/email/logo.ts: ${png.length} bytes`);
